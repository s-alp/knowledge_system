def build_workbook(output_path: Path) -> Path:
    """機能概要のxlsxを新規生成する。"""

    output_path = output_path.resolve()
    if output_path.exists():
        raise FileExistsError(f"出力先が既に存在します。上書きしません: {output_path}")
    output_path.parent.mkdir(parents=True, exist_ok=True)

    workbook = Workbook()
    builders = [
        ("00_はじめに", _build_intro),
        ("01_全体構成", _build_structure),
        ("02_読み取り元", _build_sources),
        ("03_項目一覧", _build_items),
        ("04_出力の形", _build_output),
        ("05_タグ一覧", _build_tags),
        ("06_前提と役割", _build_prerequisites),
    ]
    for index, (name, builder) in enumerate(builders):
        sheet = workbook.active if index == 0 else workbook.create_sheet()
        sheet.title = name
        sheet.sheet_view.showGridLines = False
        builder(sheet)
    workbook.active = 0
    workbook.save(output_path)
    return output_path


def main() -> int:
    parser = ArgumentParser()
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help="新規作成するxlsx。既存ファイルは上書きしない。",
    )
    args = parser.parse_args()
    print(build_workbook(args.output))
    return 0


