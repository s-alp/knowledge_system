# pptx版と同じ配色・書体にそろえ、2つの資料を並べても同じ資料群に見えるようにする。
FONT_NAME = "游ゴシック"
INK = "1F1F1F"
BLUE = "005BAC"
MUTED = "5A5A5A"
CARD_BG = "F5F7FA"
LINE = "C9D3DD"

THIN = Side(style="thin", color=LINE)
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)


def _title(sheet, row: int, text: str, subtitle: str = "") -> int:
    """シート冒頭の見出しを置き、次に書き始める行を返す。"""

    cell = sheet.cell(row=row, column=1, value=text)
    cell.font = Font(name=FONT_NAME, size=16, bold=True, color=INK)
    row += 1
    if subtitle:
        cell = sheet.cell(row=row, column=1, value=subtitle)
        cell.font = Font(name=FONT_NAME, size=10, color=MUTED)
        row += 1
    return row + 1


def _section(sheet, row: int, text: str) -> int:
    """表や本文の前に置く小見出し。"""

    cell = sheet.cell(row=row, column=1, value=text)
    cell.font = Font(name=FONT_NAME, size=12, bold=True, color=BLUE)
    return row + 1


def _paragraph(sheet, row: int, text: str, *, columns: int = 3) -> int:
    """折り返し表示の説明文を、列をまたいで置く。"""

    cell = sheet.cell(row=row, column=1, value=text)
    cell.font = Font(name=FONT_NAME, size=10, color=INK)
    cell.alignment = Alignment(wrap_text=True, vertical="top")
    sheet.merge_cells(start_row=row, start_column=1, end_row=row, end_column=columns)
    sheet.row_dimensions[row].height = 30
    return row + 2


def _table(
    sheet,
    row: int,
    headers: list[str],
    rows: list[list[str]],
    *,
    autofilter: bool = False,
    span_to: int | None = None,
) -> int:
    """見出し行を濃紺で塗った表を置き、次に書き始める行を返す。

    span_toは、列数が少ない表の最終列を、シートの右端まで広げるための指定。
    シートの列幅は一番列数の多い表に合わせるため、指定しないと2列の表だけが
    細長く折り返して読みにくくなる。
    """

    header_font = Font(name=FONT_NAME, size=10, bold=True, color="FFFFFF")
    header_fill = PatternFill("solid", fgColor=BLUE)
    for column, text in enumerate(headers, start=1):
        cell = sheet.cell(row=row, column=column, value=text)
        cell.font = header_font
        cell.fill = header_fill
        cell.border = BORDER
        cell.alignment = Alignment(vertical="center", wrap_text=True)
    if span_to is not None and len(headers) < span_to:
        sheet.merge_cells(start_row=row, start_column=len(headers), end_row=row, end_column=span_to)
        for column in range(len(headers) + 1, span_to + 1):
            sheet.cell(row=row, column=column).fill = header_fill
    sheet.row_dimensions[row].height = 22
    header_row = row
    row += 1

    stripe = PatternFill("solid", fgColor=CARD_BG)
    for index, values in enumerate(rows):
        for column, text in enumerate(values, start=1):
            cell = sheet.cell(row=row, column=column, value=text)
            cell.font = Font(name=FONT_NAME, size=10, bold=column == 1, color=INK)
            cell.border = BORDER
            cell.alignment = Alignment(vertical="top", wrap_text=True)
            if index % 2:
                cell.fill = stripe
        if span_to is not None and len(values) < span_to:
            for column in range(len(values) + 1, span_to + 1):
                filler = sheet.cell(row=row, column=column)
                filler.border = BORDER
                if index % 2:
                    filler.fill = stripe
            sheet.merge_cells(start_row=row, start_column=len(values), end_row=row, end_column=span_to)
        row += 1

    if autofilter:
        last_column = get_column_letter(len(headers))
        sheet.auto_filter.ref = f"A{header_row}:{last_column}{row - 1}"
        sheet.freeze_panes = f"A{header_row + 1}"
    return row + 1


def _widths(sheet, widths: list[float]) -> None:
    """列幅を設定し、あわせて印刷時に列が切れない設定を入れる。

    画面で読む前提の資料だが、印刷やPDF化で右端の列が別ページへ送られると
    表として読めなくなるため、横向き・幅に合わせるを既定にする。
    """

    for index, width in enumerate(widths, start=1):
        sheet.column_dimensions[get_column_letter(index)].width = width
    sheet.page_setup.orientation = "landscape"
    sheet.page_setup.fitToWidth = 1
    # 1シート1ページに収め、最後の1行だけが次ページへ送られる状態を避ける。
    sheet.page_setup.fitToHeight = 1
    sheet.sheet_properties.pageSetUpPr = PageSetupProperties(fitToPage=True)


