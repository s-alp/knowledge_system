"""エンドユーザー向けご説明と機能概要を1本にまとめた、統合版pptxを生成する。

実行目的:
- 「エンドユーザー様向けご説明」と「機能概要」の2資料を見比べないと全体が分からない、
  という状態を解消する。1つの資料だけで、課題から仕組み、前提、進め方までが読める。

つなぎ方の方針:
- 2資料を単純に並べない。同じ論点を扱っているスライドは1枚へまとめる。
  - 「根拠が残る」と「確定できないときの扱い」は、確かめ方の章として続けて置く。
  - 「必要な環境」と「どこで何が動くか」は、実行構成の表と補足カードで1枚にまとめる。
  - 「必要なもの」と「決めておくこと」は、運用として決める4点へまとめる。
- 章立てを、読む順序（困りごと → 概要 → 中身 → 出力 → 導入）で通す。
- フロー図は別章にせず、関係する章の中へ置く。業務フローは概要の締め、
  処理フローは処理の説明の直後、導入の進め方は導入章の締めに置く。
- 最初に章の一覧を置き、どこに何が書いてあるかを1枚で示す。

読み手:
- 導入先のエンドユーザー（決裁者・管理職）。開発側どうしの資料ではない。

書き分けの方針:
- 関数名、内部キー名、実装言語、ソース規模といった実装用語は載せない。
- 開発会社間の分担や納品範囲は載せない。範囲は「本機能」と「ナレッジシステム本体」の関係で書く。
- 客先名、実ファイル名、社内パスは載せない。例示は架空値に限定する。
- 記載内容は`docs/tag_extraction_and_assignment_current_spec_2026-07-29.md`の現行仕様に合わせる。

前提:
- 公式テンプレートをレイアウト継承元にする（`alpine_pptx_kit`）。
- 模擬検索画面とフロー定義は既存スクリプトから読み込み、文言を二重管理しない。
- python-pptxを利用できるPythonで、リポジトリルートから実行する。

副作用:
- 指定した新規pptxを1ファイル作成する。既存ファイルは上書きせず処理を中断する。
"""

