def _flow_slide(prs, flow) -> None:
    """A3のフロー図と同じ定義から、16:9スライド1枚を組む。

    文言をこちらへ写さずフロー定義を読むことで、A3版・機能概要版・統合版の3つで
    流れが食い違わないようにする。
    """

    slide = content_slide(prs, flow.title, flow.subtitle)
    draw_swimlane(
        slide,
        slide_geometry(flow),
        flow.lanes,
        flow.steps,
        flow.links,
        highlight_lane=flow.highlight_lane,
    )
    note(slide, 6.6, flow.footnote)


def _labeled_band(slide, y: float, height: float, label: str, items: list[str]) -> None:
    """「入力」「出力」のように、見出し付きで複数の箱を横に並べた帯を置く。"""

    textbox(
        slide,
        0.5,
        y + 0.06,
        1.25,
        0.3,
        [(label, {"size": 11.5, "bold": True, "color": BLUE})],
    )
    box_left = 1.9
    box_width = (12.83 - box_left - 0.2 * (len(items) - 1)) / len(items)
    for index, item in enumerate(items):
        x = box_left + index * (box_width + 0.2)
        box = card(slide, x, y, box_width, height, fill=CARD_BG)
        box.text_frame.vertical_anchor = MSO_ANCHOR.MIDDLE
        set_lines(
            box.text_frame,
            [(item, {"size": 11.5, "color": INK, "align": PP_ALIGN.CENTER, "space_after": 0})],
        )


def _down_arrow(slide, y: float) -> None:
    """帯と帯の間に、流れの向きを示す下向き矢印を置く。"""

    textbox(
        slide,
        0.5,
        y,
        12.33,
        0.22,
        [("▼", {"size": 11, "bold": True, "color": BLUE, "align": PP_ALIGN.CENTER, "space_after": 0})],
    )


def _column_cards(slide, y: float, height: float, items: list[tuple[str, str]], *, head_size=13.5) -> None:
    """3枚のカードを横に並べる。見出しと本文の高さは呼び出し側で決めた枠に収める。"""

    for index, (head, body) in enumerate(items):
        x = 0.5 + index * 4.17
        card(slide, x, y, 3.94, height)
        textbox(slide, x + 0.32, y + 0.26, 3.34, 0.55, [(head, {"size": head_size, "bold": True, "color": BLUE})])
        textbox(slide, x + 0.32, y + 0.92, 3.34, height - 1.1, [(body, {"size": 11.5, "color": INK})])


def _pair_cards(slide, y: float, height: float, items: list[tuple[str, str]], *, numbered=False) -> None:
    """2列×N行のカードを並べる。課題や準備事項のように、対等な項目を置く。"""

    for index, (head, body) in enumerate(items):
        column, row = index % 2, index // 2
        x = 0.5 + column * 6.25
        top = y + row * (height + 0.25)
        card(slide, x, top, 6.08, height)
        label = f"{index + 1}.　{head}" if numbered else head
        textbox(slide, x + 0.32, top + 0.26, 5.45, 0.35, [(label, {"size": 15, "bold": True, "color": BLUE})])
        textbox(slide, x + 0.32, top + 0.82, 5.45, height - 1.0, [(body, {"size": 12, "color": INK})])


